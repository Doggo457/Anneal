    def require_gate(self):
        """The loop scores rounds on the six-language gate only (21 Oct 2026), and on one gate for its whole life:
        the retired Python gate never scores a round, and a gate that changes after round 0 would make every later
        comparison meaningless. Raises Waiting otherwise."""
        if not os.path.exists(E.GATE_PATH):
            raise Waiting("the gate is not built: run scripts/setup_toolchains.py, --check, then scripts/build_gate.py")
        kinds = {it.get("kind") for it in E.read_jsonl(E.GATE_PATH)}
        if not kinds or not kinds <= set(GATE_KINDS):
            raise Waiting(f"data/eval/gate.jsonl holds {sorted(map(str, kinds))} items, not the six-language gate: run "
                          "scripts/build_gate.py (it archives the Python gate)")
        sha = file_sha(E.GATE_PATH)
        known = self.state.get("gate_sha")
        if known is None:
            self.state["gate_sha"] = sha
            self.save()
        elif known != sha:
            raise Waiting(f"data/eval/gate.jsonl changed since the rounds were scored on it ({known} -> {sha}); "
                          "restore it (rounds compare against scores on the old one)")

    def require_gate_server(self, cfg):
        """Every gate, non-coding and no-worse-check score in the loop's life comes from a gate server with the same
        settings (loop.yaml gate: slots, build and spec, 21 Oct 2026; budget, max_tokens and budget_message, and
        noncoding: max_tokens, 22 Oct 2026) on the same graphics driver (22 Oct 2026): answers differ with them, so a
        change part way would compare rounds scored differently. Recorded at the first check; rows scored before it
        was recorded came from LEGACY_GATE_SERVER's settings, and before the driver was recorded from
        llama.LEGACY_GPU_DRIVER. Raises Waiting on a change, or when the build's llama-server is missing. Slots and
        cache size (BATCH_ONLY) may change part way (26 Oct 2026: 8 at once from part way through the base pass):
        each such change goes in state["gate_server_changes"] with the gate rows scored before it."""
        want = gate_server(cfg)
        known = self.state.get("gate_server")
        if known is None:
            scored = [p for p in glob.glob(os.path.join(self.dir, "rounds", "r*", "gate.seed*.jsonl"))
                      if E.read_jsonl(p)]
            known = dict(LEGACY_GATE_SERVER) if scored else want
        else:
            known = dict(GATE_SERVER_ADDED, **known)
        diff = [k for k in want if known.get(k) != want[k] and k not in BATCH_ONLY]
        if diff:
            raise Waiting(f"experiments/loop.yaml and this PC ask for a gate server with "
                          f"{describe_gate_server(want, diff)}, but the rounds so far were scored with "
                          f"{describe_gate_server(known, diff)}: put loop.yaml's gate settings"
                          + (" and the graphics driver" if "gpu_driver" in diff else "") + " back, or set every "
                          "round's gate answers aside to score again from round 0")
        binary = llama.server_binary(want["build"])
        if want["build"] != llama.DEFAULT_BUILD and not os.path.exists(binary):
            raise Waiting(f"loop.yaml's gate.build is {want['build']}, but {binary} is missing")
        if self.state.get("gate_server") != want:
            moved = {k: [known.get(k), want[k]] for k in BATCH_ONLY if known.get(k) != want[k]}
            if moved:
                rows = sum(len(E.read_jsonl(p))
                           for p in glob.glob(os.path.join(self.dir, "rounds", "r*", "gate.seed*.jsonl")))
                self.state.setdefault("gate_server_changes", []).append(
                    {"time": time.strftime("%Y-%m-%d %H:%M:%S"), "rows_scored_before": rows, **moved})
                self.log(f"gate server: {describe_gate_server(want, list(moved))} from now on (was "
                         f"{describe_gate_server(known, list(moved))}; {rows} gate rows scored before)")
            self.state["gate_server"] = want
            self.save()

    def slot_room_check(self, url, cfg, sets):
        """Each gate server slot holds gate_ctx / slots tokens: the longest prompts of each set (label,
        items, max_tokens) with a whole answer must fit, or long answers would be cut short. Raises Waiting."""
        room = gate_ctx(cfg) // gate_slots(cfg)
        for label, items, max_tokens in sets:
            texts = sorted((room_text(it) for it in items), key=len, reverse=True)[:3]
            if not texts:
                continue
            need = (max(ew.count_tokens(url, t) for t in texts) + PROMPT_MARGIN + int(max_tokens)
                    + (TOOLS_MARGIN if any(it.get("tools") for it in items) else 0))
            if need > room:
                raise Waiting(f"the longest {label} prompt with a whole answer needs {need} tokens, over the {room} "
                              f"each of the {gate_slots(cfg)} gate server slots holds: lower gate.slots or raise gate.ctx in "
                              "experiments/loop.yaml")
            self.log(f"{label}: the longest prompt with a whole answer needs {need} of the {room} tokens a slot holds")

    def toolchain_check(self, gate):
        """Before a gate pass with write or fix items: the code sandbox can't write to its own storage folder (closed
        again if it can), the toolchains are the ones every earlier round was judged with (anneal/polyglot.py
        toolchain_fingerprint), and two smoke programs per language (one right, one wrong) get their verdicts in the
        sandbox, and one program that tries to leave the sandbox is stopped. CPU only, under a minute. Returns the
        fingerprint (None for the old gate)."""
        langs = sorted({it["lang"] for it in gate if it.get("kind") in GATE_KINDS})
        if not langs:
            return None
        sandbox.ensure_private_folder_closed(self.log)
        from anneal import polyglot as P
        from anneal import polyglot_smoke as S
        fp = P.toolchain_fingerprint()
        if fp is None:
            raise Waiting("sandbox/toolchains/lock.json is missing: run scripts/setup_toolchains.py")
        known = self.state.get("toolchains")
        if known is None:
            self.state["toolchains"] = fp
            self.save()
        elif known != fp:
            raise Waiting(f"the toolchains changed since the rounds were judged ({known} -> {fp}); restore them "
                          "(sandbox/toolchains/lock.json)")
        ex, tc, bad = P.SandboxExecutor(), P.Toolchain.windows(), []
        for lang in langs:
            for prog in S.programs(lang):
                if not (prog["name"] in ("sum64", "wrong") or (prog["name"] == "isolation" and lang == langs[0])):
                    continue
                v = P.judge(lang, prog["code"], prog["cases"], ex, tc, case_timeout_s=prog.get("timeout", 10.0),
                            all_cases=True)
                if v.stage != prog["expect"]:
                    bad.append(f"{lang} {prog['name']}: {v.stage} (want {prog['expect']}) {v.detail[-200:]}")
        if bad:
            raise RuntimeError("toolchain smoke check failed: " + "; ".join(bad))
        return fp

