"""Keep-if-better improvement loop (Anneal): train a round, test it on held-out problems, keep it only if it is clearly
better than the best so far, and go again for as long as it is left running. Launched from the Training page as the
run "loop" (run folder results/loop); restarted after a reboot by scripts/loop_watchdog.py.

My rule (18 Oct 2026): "train and then test it if it higher scoring the new model is kept and then trained on
again to improve it more if its worse scoring then its deleted so it progressively gets better over time".
Data (19 Oct 2026): public datasets only: no rows generated by the base model and none generated for this project.

Rounds (results/loop/rounds/rNNN):
  r000 base         the base model on the gate and the non-coding check: the first "best", and the non-coding
                    reference for every later round. Then the base on each no-worse check in loop.yaml's guards
                    (guards_base_in_round_0), so every check has run end to end before a round depends on it.
  r001 first-run    the first run's adapter on the same sets, for the record (it trained on self-generated rows, so it
                    never becomes the best).
  r002 onwards      plan -> data -> train -> convert -> valloss -> sweloss -> termloss -> evaluate -> decide
                    [-> bfcl -> cweval -> milestone -> confirm] -> finish
    plan       recipe: the next unused entry of `recipes` in experiments/loop.yaml whose condition holds (after_kept,
               after_dropped_stacks), else `default_recipe`. Init: the best adapter (training continues from it), or
               the base when the best is the base or the recipe changes the LoRA shape ("base_lineage": retrain from
               the base on every slice the best was built from + new rows). Later rounds inherit a kept LoRA shape.
               Data: the next unused rows of each public source pool, split at a fixed ratio: when a source runs out
               the round shrinks (others in its `group` stand in) rather than other sources taking its share. A round
               that continues the best adapter also mixes back in `replay_fraction` x (new rows) of the rows the best
               was built from (19 Oct 2026: kept rows carry forward).
               Rejected rows roll forward (research/growing-data-rounds.md): a rejected round's new rows join the next
               round that draws from the default sources (the same best, plus fresh rows), up to `stack_max_new_rows`
               new rows; a reject at the cap drops the stack for good. On 495 problems a real 2-point gain is kept
               only 24-44% of the time, so a reject mostly means "too small to see" and a bigger step is the useful
               next try. When the pools can't fill a round, a `when_pools_short` recipe (two passes over what is left)
               runs once before the loop waits.
    data       slices of the source pools (data/processed/loop/SOURCE, prepared once by prepare_dataset.py or
               public_source.py with EvalPlus and held-out decontamination) mixed by mix_datasets.py.
    train      train_longrun.py (the `train` settings + the recipe's overrides, init_adapter for a continued adapter).
    convert    adapter -> GGUF LoRA (llama.cpp convert_lora_to_gguf.py).
    valloss    answer-token loss on the round's val rows, base vs adapter (scripts/val_loss.py); for the record.
    sweloss    loss on the held-out bug-fix steps (data/eval/swe_heldout.jsonl, scripts/build_swe_heldout.py: Open-SWE
               runs from repositories no round trains on), this adapter against the best so far: the base's losses
               (scored once, in the first round) while the base is the best, then the kept round's own.
    termloss   the same on the held-out terminal steps (data/eval/term_heldout.jsonl, scripts/build_swe_heldout.py
               --set terminal: GLM-5.3 runs from task groups no round trains on), 21 Oct 2026: the six-language gate
               can't see terminal skill.
    evaluate   one llama-server with --lora: 3 sample generations, the gate (seed = the best's reference seed), the
               non-coding check (seeds 1 and 2). The gate (scripts/build_gate.py, 21 Oct 2026) asks for programs in
               C++, Java, Go, Rust, JavaScript and TypeScript (write items) and for fixes of wrong C++ and Java
               submissions (fix items), built and run in the sandbox (anneal/polyglot.py). Before each gate pass the
               toolchains must be the ones every earlier round was judged with, and two smoke programs per language
               must get their verdicts.
    decide     anneal/evalsets.decide, two ways to keep: the gate path (gate higher, one-sided sign test p <= alpha) or
               the loss path (rules.loss_rule, 21 Oct 2026: gate not lower, and the held-out bug-fix loss or the
               held-out terminal loss lower on more steps than chance, Holm-adjusted across the two, p <= loss_alpha).
               Either way the write and fix parts and the non-coding check are not worse beyond tolerance nor
               significantly worse, and the samples are clean.
    bfcl       (passed decide) the no-worse checks in loop.yaml's guards, 21 Oct 2026, in GUARDS order: BFCL's 150
    cweval     Java and JavaScript function calls (anneal/bfcl.py), then CWEval's 32 Go and JavaScript secure-coding
               tasks (anneal/cweval.py). Same rule as EvalPlus, on the gate's server settings, paired per item against
               the base's rows (scored once, in round 0 or the first round that needs them, and again only if the
               settings change). They run before EvalPlus, the longest check (21 Oct 2026): a blocked round skips the
               checks after it, EvalPlus and the confirm pass. Every check must pass either way, so the order changes no
               decision.
    milestone  (passed decide and the checks above) EvalPlus HumanEval+ / MBPP+ seed 1 on the first run's exact
               scoring server, paired against the base's first-run EvalPlus answers (on another graphics driver,
               against the base's answers on that driver, answered once, 22 Oct 2026). Since 21 Oct 2026 a no-worse
               check only (the base already passes about 86% of the plus tests, so it can't show much gain): with
               rules.evalplus_guard a drop beyond evalplus_tolerance, or a significant one, rejects the round
               (evalsets.guard_check). It runs before confirm, so a blocked round skips the second gate pass.
    confirm    (kept) the gate again with a fresh seed; those rows become the best's reference, so the next round is
               compared against an unbiased score, not the lucky draw that got this one kept. With
               rules.confirm_net_win the fresh-seed rows of a round kept on the gate path must also win more problems
               than they lose against the best's reference, or the round is rejected (offsets the extra tries that
               rolling rows forward gives).
    finish     state.json updated (best, rejects in a row); a rejected round's adapter, checkpoints and GGUF are
               deleted (its scores, logs and report stay); report.md and results/loop/summary.md written.

Prototype rounds (loop.yaml prototype_rounds, 27 Oct 2026; round 2, the first training round): the whole gate is
answered (no early look), every no-worse check and EvalPlus run whatever decide says and even after one of them is
worse, and a rejected prototype keeps its adapter, checkpoints and GGUF. The keep rule is unchanged: it still decides
whether the round becomes the best, so what the next round continues from, and the confirm pass runs only for a keep.

Every stage leaves rNNN/stages/STAGE.done.json and is skipped after that; stages resume inside (training from its
checkpoint, scoring by problem). STOP (the Training page's Pause) stops cleanly. A stage that fails is retried once
with a fresh server; a round that fails 3 times is marked failed and the loop moves to the next round. When there are
not enough unused rows, or too little disk, the loop ends with state "waiting" and the watchdog starts it again
after experiments/loop.yaml changes.

  loop.py [--run-dir results/loop] [--resume] [--prepare-only] [--max-rounds N]
"""

