class Waiting(Exception):
    """Nothing useful to do until something changes (config, data, disk): end with state "waiting"."""


def require_script(name, marker):
    """The loop needs the 19 Oct versions of prepare_dataset.py (--where, --decontaminate-gate) and train_longrun.py
    (init_adapter). They wait in staged/ until the first run no longer loads them, and loop_watchdog.py installs them;
    until then the loop waits instead of running an old script that would ignore the new settings."""
    with open(os.path.join(ROOT, "scripts", name), encoding="utf-8") as fh:
        if marker not in fh.read():
            raise Waiting(f"scripts/{name} is the version without {marker!r}; loop_watchdog.py installs staged/{name} "
                          f"once the first run no longer needs the old one")


def load_config(path=CONFIG):
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def write_json(path, data):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=1, default=str)
    os.replace(tmp, path)


def pid_alive(pid):
    if not pid:
        return False
    if os.name == "nt":
        import ctypes
        h = ctypes.windll.kernel32.OpenProcess(0x1000, False, int(pid))  # PROCESS_QUERY_LIMITED_INFORMATION
        if not h:
            return False
        code = ctypes.c_ulong()
        ok = ctypes.windll.kernel32.GetExitCodeProcess(h, ctypes.byref(code))
        ctypes.windll.kernel32.CloseHandle(h)
        return bool(ok) and code.value == 259  # STILL_ACTIVE
    try:
        os.kill(int(pid), 0)
        return True
    except OSError:
        return False


def spec_hash(src):
    keep = {k: v for k, v in src.items() if k not in ("share", "note")}
    return hashlib.sha256(json.dumps(keep, sort_keys=True).encode("utf-8")).hexdigest()[:16]


def lora_shape(train_cfg):
    return {k: train_cfg.get(k) for k in ("lora_r", "lora_alpha", "target_modules")}


