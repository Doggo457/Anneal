def plan_counts(cfg, recipe, state, pool_rows):
    """{source: rows to take} for this round, split by shares among the sources with rows left."""
    rows = int(recipe.get("rows") or cfg["rows_per_round"])
    shares = recipe.get("mix") or {s["name"]: s.get("share", 1.0) for s in cfg.get("sources") or []}
    left = {n: pool_rows.get(n, 0) - state["offsets"].get(n, 0) for n in shares}
    live = {n: float(w) for n, w in shares.items() if w and left.get(n, 0) > 0}
    total_w = sum(live.values())
    return {n: min(left[n], int(round(rows * w / total_w))) for n, w in live.items()} if live else {}


def row_key(row):
    """What makes a row "the same data": the question for single-turn rows, the first user message + the trained
    turn for multi-turn rows (each step of an agent session is its own row)."""
    msgs = row.get("messages") or []
    users = [m for m in msgs if m.get("role") == "user"]
    if not users:
        return None
    if len(users) == 1 and sum(m.get("role") == "assistant" for m in msgs) == 1:
        text = users[0].get("content") or ""
    else:
        last = msgs[-1]
        text = (users[0].get("content") or "") + "\n#\n" + (last.get("content") or "") + json.dumps(last.get("tool_calls") or [])
    return hashlib.sha1(text.strip().lower().encode("utf-8")).hexdigest()


def pick_rows(path, start, n, used):
    """Indices of the next n rows from `start` whose key is not in `used` (adds their keys). Returns (indices, the
    offset to start from next time)."""
    out, nxt, idx = [], start, 0
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            if idx >= start:
                if len(out) >= n:
                    break
                nxt = idx + 1
                k = row_key(json.loads(line))
                if k is not None and k not in used:
                    used.add(k)
                    out.append(idx)
            idx += 1
    return out, nxt


def rows_at(path, indices):
    """The rows at these indices of a JSONL file (indices count non-empty lines), in the order given."""
    want = set(indices)
    got = {}
    last = max(indices) if indices else -1
    with open(path, encoding="utf-8") as fh:
        idx = 0
        for line in fh:
            if not line.strip():
                continue
            if idx in want:
                got[idx] = json.loads(line)
            idx += 1
            if idx > last:
                break
    return [got[i] for i in indices if i in got]


def pick_replay(lineage, n, seed):
    """n rows drawn without replacement (random.Random(seed)) from the rows the best adapter was built from
    (lineage: [[source, [row indices]], ...]), grouped by source in lineage order: [[source, [indices]], ...]."""
    flat = [(name, i) for name, idx in lineage for i in idx]
    if n <= 0 or not flat:
        return []
    pick = set(random.Random(seed).sample(range(len(flat)), min(n, len(flat))))
    out = {}
    for k, (name, i) in enumerate(flat):
        if k in pick:
            out.setdefault(name, []).append(i)
    return [[name, idx] for name, idx in out.items()]


def choose_init(recipe, best, train_cfg):
    """"base" (best is the base), "best" (continue the best adapter) or "base_lineage" (retrain from the base on the
    best's data + new rows, when the recipe asks or the LoRA shape changes)."""
    if best.get("adapter") is None:
        return "base"
    want = recipe.get("init", "best")
    if want == "base_lineage" or lora_shape(train_cfg) != best.get("lora_shape"):
        return "base_lineage"
    return "best"


def safe_delete(round_dir, rel_paths, log=print):
    """Delete only paths inside this round's folder."""
    root = os.path.realpath(round_dir)
    freed = 0
    for rel in rel_paths:
        p = os.path.realpath(os.path.join(round_dir, rel))
        if not p.startswith(root + os.sep) or not os.path.exists(p):
            continue
        if os.path.isdir(p):
            for dp, _, fs in os.walk(p):
                freed += sum(os.path.getsize(os.path.join(dp, f)) for f in fs)
            shutil.rmtree(p)
        else:
            freed += os.path.getsize(p)
            os.remove(p)
        log(f"deleted {p}")
    return freed


class Loop(fr.Controller):
    def __init__(self, args, run):
        super().__init__(args, run)
        self.rdir = None
        self.rnum = None
        self.state_path = os.path.join(self.dir, "state.json")
        self.state = self.read_json(self.state_path) or {
            "version": 1, "base": None, "best": None, "rounds": [], "offsets": {}, "recipes_done": [],
            "rejects_in_row": 0, "created": time.strftime("%Y-%m-%d %H:%M:%S")}

    # ----------------------------------------------------------------------------------------- plumbing

    def save(self):
        write_json(self.state_path, self.state)

    def done_path(self, stage):
        return os.path.join(self.rdir, "stages", f"{stage}.done.json")

    def mark_done(self, stage, data):
        os.makedirs(os.path.join(self.rdir, "stages"), exist_ok=True)
        data = dict(data, finished=time.strftime("%Y-%m-%d %H:%M:%S"))
        write_json(self.done_path(stage), data)
        self.run.metric(event="stage_done", round=self.rnum, stage=stage)
        return data

    def status(self, stage, detail=""):
        stages = REF_STAGES if self.rnum is not None and self.rnum < 2 else ROUND_STAGES
        self.run.write_status(state="running", round=self.rnum, stage=stage, step=stages.index(stage) + 1,
                              max_steps=len(stages), detail=f"round {self.rnum}: {stage}" + (f", {detail}" if detail else ""),
                              best_round=(self.state.get("best") or {}).get("round"))

    def run_child(self, cmd, log_name, stop_dir=None, monitor=None, interval=30):
        # the round's own logs folder, else first_run's plumbing unchanged
        logs = os.path.join(self.rdir or self.dir, "logs")
        os.makedirs(logs, exist_ok=True)
        saved, self.dir = self.dir, os.path.dirname(logs)
        try:
            return super().run_child(cmd, log_name, stop_dir, monitor, interval)
        finally:
            self.dir = saved

    def serve(self, flags, name, coopmat=False):
        return super().serve(flags, f"r{self.rnum:03d}-{name}", coopmat)

    def round_record(self):
        for r in self.state["rounds"]:
            if r["round"] == self.rnum:
                return r
        rec = {"round": self.rnum, "status": "running", "failures": 0, "started": time.strftime("%Y-%m-%d %H:%M:%S")}
        self.state["rounds"].append(rec)
        self.save()
        return rec

    def enter_round(self, n):
        self.rnum = n
        self.rdir = os.path.join(self.dir, "rounds", f"r{n:03d}")
        os.makedirs(os.path.join(self.rdir, "stages"), exist_ok=True)

    def free_gb(self):
        return shutil.disk_usage(ROOT).free / 2 ** 30

    def gate_flags(self, cfg, lora=None):
        g = cfg["gate"]
        return llama.scoring_flags(lora=lora, extra=["--reasoning-budget", str(g["budget"])] + fr.SAMPLER_FLAGS)

    def run_stage(self, name, fn, *a):
        if self.done(name) is not None:
            return self.done(name)
        self.check_stop()
        self.log(f"== round {self.rnum}: {name}")
        self.status(name)
        self.run.metric(event="stage_start", round=self.rnum, stage=name)
        for attempt in range(2):
            try:
                return fn(*a)
            except (fr.Paused, ew.Stopped, E.Stopped):
                raise fr.Paused()
            except Waiting:
                raise
            except Exception as exc:
                self.unserve()
                if attempt == 1 or self.stopping() or name in ("train", "finish", "plan"):
                    raise
                self.log(f"stage {name} failed ({type(exc).__name__}: {exc}); retrying once with a fresh server")

    # ----------------------------------------------------------------------------------------- data pools

    def pool_dir(self, src):
        return os.path.join(POOLS, src["name"])

    def pool_rows(self, cfg):
        out = {}
        for src in cfg.get("sources") or []:
            info = self.read_json(os.path.join(self.pool_dir(src), "pool.json"))
            if info and info.get("spec") == spec_hash(src):
                out[src["name"]] = info["train_rows"]
        return out

    def prepare_pools(self, cfg):
        """Prepare every source pool not yet prepared (CPU only)."""
        for src in cfg.get("sources") or []:
            d = self.pool_dir(src)
            info = self.read_json(os.path.join(d, "pool.json"))
            if info:
                if info.get("spec") != spec_hash(src):
                    raise RuntimeError(f"source {src['name']} changed since its pool was prepared; give the changed "
                                       f"source a new name (rows already used keep their meaning)")
                continue
            self.check_stop()
            seq = int(cfg["train"]["seq_len"])
            common = ["--tokenizer", fr.SNAP, "--max-tokens", str(seq), "--decontaminate",
                      "--decontaminate-gate", E.DECONTAM_EXTRA, "--out", d]
            if src["kind"] == "fields":
                require_script("prepare_dataset.py", "--decontaminate-gate")
                cmd = [PY, "-u", os.path.join(ROOT, "scripts", "prepare_dataset.py"), "--dataset", src["dataset"],
                       "--prompt-field", src["prompt_field"], "--response-field", src["response_field"],
                       "--max-samples", str(src["pool_rows"]), "--max-per-prompt", str(src.get("max_per_prompt", 1)),
                       "--seed", str(src.get("seed", 42))] + common
                for k, flag in (("config", "--config"), ("split", "--split"), ("data_files", "--data-files"),
                                ("reasoning_field", "--reasoning-field")):
                    if src.get(k):
                        cmd += [flag, str(src[k])]
                if src.get("require_think", True):
                    cmd.append("--require-think")
                for w in src.get("where") or []:
                    cmd += ["--where", w]
            elif src["kind"] == "messages":
                cmd = [PY, "-u", os.path.join(ROOT, "scripts", "public_source.py"), "--dataset", src["dataset"],
                       "--files", src["files"], "--messages-field", src.get("messages_field", "messages"),
                       "--turns", src.get("turns", "last"), "--min-target-chars", str(src.get("min_target_chars", 0)),
                       "--max-rows", str(src["pool_rows"])] + common
                if src.get("revision"):
                    cmd += ["--revision", src["revision"]]
                for t in src.get("drop_tool_names") or []:
                    cmd += ["--drop-tool-name", t]
                for w in src.get("where") or []:
                    cmd += ["--where", w]
                if src.get("max_files"):
                    cmd += ["--max-files", str(src["max_files"])]
                if src.get("require_think", True):
                    cmd.append("--require-think")
            else:
                raise RuntimeError(f"source {src['name']}: unknown kind {src['kind']!r}")
            if not os.path.exists(E.DECONTAM_EXTRA):
                raise RuntimeError(f"{E.DECONTAM_EXTRA} is missing: run scripts/build_evalsets.py first")
            self.log(f"preparing pool {src['name']}")
            rc = self.run_child(cmd, f"pool-{src['name']}.log")
            self.check_stop()
            if rc != 0:
                raise RuntimeError(f"pool {src['name']}: exit code {rc} (log {self.rdir or self.dir}/logs/pool-{src['name']}.log)")
            n = self.count_lines(os.path.join(d, "train.jsonl"))
            min_rows = int(src.get("min_pool_rows", 500))
            write_json(os.path.join(d, "pool.json"), {"spec": spec_hash(src), "source": src, "train_rows": n,
                                                      "val_rows": self.count_lines(os.path.join(d, "val.jsonl")),
                                                      "usable": n >= min_rows,
                                                      "prepared": time.strftime("%Y-%m-%d %H:%M:%S")})
            self.log(f"pool {src['name']}: {n} train rows" + ("" if n >= min_rows else f" (under {min_rows}: unused)"))

    # ----------------------------------------------------------------------------------------- scoring

    def evaluate_model(self, cfg, gguf, gate_seed, samples=True):
        """Samples (optional), the gate at gate_seed and the non-coding check, on one server. Resumable."""
        out = {}
        gate = E.read_jsonl(E.GATE_PATH)
        nc = E.read_jsonl(E.NONCODING_PATH)
        if not gate or not nc:
            raise RuntimeError("held-out sets missing: run scripts/build_evalsets.py")
        g = cfg["gate"]
        self.serve(self.gate_flags(cfg, lora=gguf), "evaluate")
        try:
            url = self.server.url
            if samples:
                sp = os.path.join(self.rdir, "samples.json")
                ss = self.read_json(sp)
                if ss is None:
                    ss = []
                    for name, prompt in fr.SANITY_PROMPTS:
                        self.check_stop()
                        r = ew.chat_request(url, prompt, seed=7, max_tokens=g["max_tokens"])
                        ss.append(dict(name=name, finish_reason=r["finish_reason"], completion_tokens=r["completion_tokens"],
                                       reasoning_chars=len(r["reasoning"]), content_chars=len(r["content"]),
                                       loop_suspect=fr.loop_suspect(r["reasoning"]) or fr.loop_suspect(r["content"]),
                                       content_head=r["content"][:600]))
                    write_json(sp, ss)
                out["samples_ok"] = all(s["finish_reason"] == "stop" and s["reasoning_chars"] > 0
                                        and s["content_chars"] > 0 and not s["loop_suspect"] for s in ss)
                out["samples"] = ss
            chat = lambda u, m, seed, mt: ew.chat_request(u, m, seed, mt)  # noqa: E731
            check = E.gate_check(gt.run_io_tests, gt.run_assert_tests, gt.extract_code)
            gpath = os.path.join(self.rdir, f"gate.seed{gate_seed}.jsonl")
            E.score(url, gate, gpath, gate_seed, g["max_tokens"], check, chat, ew.count_tokens, g["budget"],
                    concurrency=g.get("concurrency", 4), stop_check=self.stopping, log=self.log,
                    on_row=lambda r, n, tot, tps: (self.run.metric(stage="gate", round=self.rnum, done=n, of=tot,
                                                                   tok_s=round(tps, 2)),
                                                   self.status("evaluate", f"gate {n}/{tot}")))
            npath = os.path.join(self.rdir, "noncoding.jsonl")
            for s in cfg["noncoding"]["seeds"]:
                E.score(url, nc, npath, s, cfg["noncoding"]["max_tokens"], E.mc_check, chat, ew.count_tokens,
                        g["budget"], concurrency=g.get("concurrency", 4), stop_check=self.stopping, log=self.log,
                        on_row=lambda r, n, tot, tps, s=s: self.status("evaluate", f"non-coding seed {s}: {n}/{tot}"))
        finally:
            self.unserve()
        gate_rows = [r for r in E.read_jsonl(gpath) if r["seed"] == gate_seed]
        nc_rows = E.read_jsonl(npath)
        out.update(gate_rows=gpath, gate_seed=gate_seed, noncoding_rows=npath,
                   gate_pass=sum(r["pass"] for r in gate_rows), gate_n=len(gate_rows),
                   noncoding_accuracy=E.mc_accuracy(nc_rows),
                   gate_budget_hits=sum(r["budget_hit"] for r in gate_rows),
                   gate_finish=dict(_count(r["finish_reason"] for r in gate_rows)))
        return out

    # ----------------------------------------------------------------------------------------- reference rounds

    def reference_rounds(self, cfg):
        # r000: the base
        self.enter_round(0)
        rec = self.round_record()
        rec.update(name="base", kind="reference")
        if self.done("finish") is None:
            ev = self.run_stage("evaluate", lambda: self.mark_done("evaluate", self.evaluate_model(cfg, None, cfg["gate"]["seed"], samples=False)))
            self.state["base"] = {"gate_rows": ev["gate_rows"], "gate_seed": ev["gate_seed"],
                                  "noncoding_rows": ev["noncoding_rows"]}
            if self.state.get("best") is None:
                self.state["best"] = {"round": 0, "name": "base", "adapter": None, "gguf": None,
                                      "gate_rows": ev["gate_rows"], "gate_seed": ev["gate_seed"], "lineage": [],
                                      "lora_shape": None}
            rec.update(status="reference", gate=f"{ev['gate_pass']}/{ev['gate_n']}",
                       noncoding=ev["noncoding_accuracy"], finished=time.strftime("%Y-%m-%d %H:%M:%S"))
            self.save()
            self.mark_done("finish", {})
            self.write_summary()
        # r001: the first run's adapter, for the record
        if not cfg.get("score_first_run", True):
            return
        self.enter_round(1)
        if self.done("finish") is not None:
            return
        fdir = cfg.get("first_run_dir") or os.path.join(RESULTS_DIR, "first-run")
        gguf = (self.read_json(os.path.join(fdir, "stages", "convert.done.json")) or {}).get("gguf") or ""
        st = self.read_json(os.path.join(fdir, "status.json")) or {}
        rec = self.round_record()
        rec.update(name="first-run", kind="record")
        if not os.path.exists(gguf) or st.get("state") != "finished":
            rec.update(status="skipped", note=f"first run not finished (state {st.get('state')}) or no GGUF")
            self.save()
            self.mark_done("finish", {"skipped": True})
            return
        ev = self.run_stage("evaluate", lambda: self.mark_done("evaluate", self.evaluate_model(cfg, gguf, self.state["best"]["gate_seed"])))
        d = self.run_stage("decide", lambda: self.mark_done("decide", self.decision(cfg, ev)))
        rec.update(status="record", gate=f"{ev['gate_pass']}/{ev['gate_n']}", noncoding=ev["noncoding_accuracy"],
                   would_keep=d["keep"], p=d["gate"]["p_one_sided"], finished=time.strftime("%Y-%m-%d %H:%M:%S"))
        self.save()
        self.write_report(cfg, rec, ev, d)
        self.mark_done("finish", {})
        self.write_summary()

    def decision(self, cfg, ev):
        best_rows = E.read_jsonl(self.state["best"]["gate_rows"])
        best_rows = [r for r in best_rows if r["seed"] == self.state["best"]["gate_seed"]]
        cand_rows = [r for r in E.read_jsonl(ev["gate_rows"]) if r["seed"] == ev["gate_seed"]]
        base_nc = E.read_jsonl(self.state["base"]["noncoding_rows"])
        cand_nc = E.read_jsonl(ev["noncoding_rows"])
        d = E.decide(best_rows, cand_rows, base_nc, cand_nc, cfg["rules"], ev.get("samples_ok", True))
        d["best_round"] = self.state["best"]["round"]
        if not d["gate"]["n"]:
            raise RuntimeError("no gate problems in common between the best and this round")
        self.log(f"round {self.rnum}: {'KEEP' if d['keep'] else 'reject'} - gate {d['gate']['best']:.4f} -> "
                 f"{d['gate']['candidate']:.4f} ({d['gate']['wins']} wins / {d['gate']['losses']} losses, p "
                 f"{d['gate']['p_one_sided']:.4f}); reasons: {d['reasons']}")
        return d

    # ----------------------------------------------------------------------------------------- training rounds

    def next_round_number(self):
        nums = [r["round"] for r in self.state["rounds"]]
        open_ = [r["round"] for r in self.state["rounds"] if r["status"] == "running"]
        if open_:
            return min(open_)
        return max([1] + nums) + 1

    def training_round(self, cfg):
        self.enter_round(self.next_round_number())
        rec = self.round_record()
        if rec["failures"] >= MAX_ROUND_FAILURES:
            rec.update(status="failed", finished=time.strftime("%Y-%m-%d %H:%M:%S"))
            plan = self.done("plan")
            if plan and plan["recipe"]["id"] != "default" and plan["recipe"]["id"] not in self.state["recipes_done"]:
                self.state["recipes_done"].append(plan["recipe"]["id"])
            self.save()
            self.write_summary()
            return
        try:
            self._training_round(cfg, rec)
        except (fr.Paused, Waiting):
            raise
        except BaseException as exc:
            rec["failures"] = rec.get("failures", 0) + 1
            rec["last_error"] = f"{type(exc).__name__}: {exc}"
            self.save()
            raise

    def _training_round(self, cfg, rec):
        plan = self.run_stage("plan", self.plan, cfg)
        rec.update(recipe=plan["recipe"]["id"], init=plan["init"], rows=plan["rows"])
        self.save()
        self.run_stage("data", self.data, cfg, plan)
        if self.free_gb() < cfg.get("min_free_gb", 60) and self.done("train") is None:
            raise Waiting(f"only {self.free_gb():.0f} GB free on the training drive (need {cfg.get('min_free_gb', 60)})")
        self.run_stage("train", self.train_round, cfg, plan)
        self.run_stage("convert", self.convert_round)
        if cfg.get("valloss", True):
            self.run_stage("valloss", self.valloss)
        ev = self.run_stage("evaluate", lambda: self.mark_done("evaluate", self.evaluate_model(
            cfg, self.round_gguf(), self.state["best"]["gate_seed"])))
        d = self.run_stage("decide", lambda: self.mark_done("decide", self.decision(cfg, ev)))
        conf = mile = None
        if d["keep"]:
            conf = self.run_stage("confirm", self.confirm, cfg, d)
            if cfg.get("milestone_evalplus", True):
                mile = self.run_stage("milestone", self.milestone, cfg)
        self.run_stage("finish", self.finish, cfg, plan, ev, d, conf, mile)

    def plan(self, cfg):
        self.prepare_pools(cfg)
        best = self.state["best"]
        usable = {n: c for n, c in self.pool_rows(cfg).items()
                  if (self.read_json(os.path.join(POOLS, n, "pool.json")) or {}).get("usable", True)}
        used = self.used_keys()
        while True:
            recipe = pick_recipe(cfg, self.state)
            counts = plan_counts(cfg, recipe, self.state, usable)
            if sum(counts.values()) or recipe["id"] == "default":
                break
            # a queued recipe whose sources have no usable rows (e.g. a pool under its minimum): skip it, don't stall
            self.log(f"recipe {recipe['id']}: no usable rows in {recipe.get('mix')}; skipped")
            self.state["recipes_done"].append(recipe["id"])
            self.state.setdefault("recipes_skipped", []).append(recipe["id"])
            self.save()
        tcfg = effective_train(cfg, recipe)
        init = choose_init(recipe, best, tcfg)
        slices, offsets, new_keys = {}, {}, set(used)
        for n, take in counts.items():
            idx, nxt = pick_rows(os.path.join(POOLS, n, "train.jsonl"), self.state["offsets"].get(n, 0), take, new_keys)
            offsets[n] = nxt
            if idx:
                slices[n] = idx
        n_new = sum(len(v) for v in slices.values())
        if n_new < int(cfg.get("min_rows_per_round", 500)):
            raise Waiting(f"only {n_new} unused public rows available (need {cfg.get('min_rows_per_round', 500)}); "
                          "add sources to experiments/loop.yaml")
        self.state["offsets"].update(offsets)
        self.add_used_keys(new_keys - used)
        lineage = best["lineage"] if init == "base_lineage" else []
        frac = float(recipe.get("replay_fraction", cfg.get("replay_fraction", 0)) or 0)
        replay = pick_replay(best["lineage"], int(round(frac * n_new)), self.rnum) if init == "best" else []
        plan = {"recipe": recipe, "init": init, "init_adapter": best["adapter"] if init == "best" else None,
                "slices": slices, "lineage": lineage, "replay": replay,
                "rows": n_new + sum(len(ix) for _, ix in lineage) + sum(len(ix) for _, ix in replay),
                "best_round": best["round"], "train": tcfg}
        self.save()  # offsets advance with the plan, so a crash never hands these rows to another round
        return self.mark_done("plan", plan)

    def used_keys(self):
        """Keys (row_key) of every row any round or earlier run has trained on: never handed out again."""
        path = os.path.join(self.dir, "used_keys.txt")
        if not os.path.exists(path):
            keys = set()
            for f in sorted(glob.glob(os.path.join(ROOT, "data", "processed", "*", "*.jsonl"))):
                if os.path.basename(f) in ("train.jsonl", "val.jsonl"):
                    for r in E.read_jsonl(f):
                        k = row_key(r)
                        if k:
                            keys.add(k)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write("".join(k + "\n" for k in sorted(keys)))
            self.log(f"used rows: {len(keys)} keys from data/processed/*/ (everything trained on before the loop)")
        with open(path, encoding="utf-8") as fh:
            return {line.strip() for line in fh if line.strip()}

    def add_used_keys(self, keys):
        with open(os.path.join(self.dir, "used_keys.txt"), "a", encoding="utf-8") as fh:
            fh.write("".join(k + "\n" for k in sorted(keys)))

    def data(self, cfg, plan):
        root = os.path.join(self.rdir, "data")
        parts = {}
        for name, idx in plan["lineage"]:
            parts.setdefault(name, []).extend(idx)
        for name, idx in plan["slices"].items():
            parts.setdefault(name, []).extend(idx)
        for name, idx in plan.get("replay") or []:
            parts.setdefault(name, []).extend(idx)
        cmd = [PY, "-u", os.path.join(ROOT, "scripts", "mix_datasets.py"), "--tokenizer", fr.SNAP,
               "--val-per-source", str(cfg.get("val_rows_per_source", 50)), "--out", os.path.join(root, "mix")]
        for name, idx in parts.items():
            rows = rows_at(os.path.join(POOLS, name, "train.jsonl"), idx)
            if len(rows) != len(idx):
                raise RuntimeError(f"pool {name}: expected {len(idx)} rows, read {len(rows)}")
            E.write_jsonl(os.path.join(root, name, "train.jsonl"), rows)
            E.write_jsonl(os.path.join(root, name, "val.jsonl"), E.read_jsonl(os.path.join(POOLS, name, "val.jsonl")))
            cmd += ["--source", f"{name}={os.path.join(root, name)}:all"]
        rc = self.run_child(cmd, "mix.log")
        if rc != 0:
            raise RuntimeError(f"mix_datasets.py exited with {rc}")
        mix = os.path.join(root, "mix")
        return self.mark_done("data", {"train_rows": self.count_lines(os.path.join(mix, "train.jsonl")),
                                       "val_rows": self.count_lines(os.path.join(mix, "val.jsonl")),
                                       "card": open(os.path.join(mix, "data_card.md"), encoding="utf-8").read()})

    def train_round(self, cfg, plan):
        tdir = os.path.join(self.rdir, "train")
        os.makedirs(tdir, exist_ok=True)
        t = copy.deepcopy(plan["train"])
        mix = os.path.join(self.rdir, "data", "mix")
        t.update(run_name=f"loop-r{self.rnum:03d}", train_file=os.path.join(mix, "train.jsonl").replace("\\", "/"),
                 val_file=os.path.join(mix, "val.jsonl").replace("\\", "/"))
        if plan["init_adapter"]:
            require_script("train_longrun.py", "def load_init_adapter")
            t["init_adapter"] = plan["init_adapter"].replace("\\", "/")
        if lora_shape(t) != lora_shape(cfg["train"]):
            t.pop("expect_trainable_params", None)  # only valid for the default LoRA shape
        ypath = os.path.join(self.rdir, "train.yaml")
        with open(ypath, "w", encoding="utf-8") as fh:
            fh.write(f"# loop round {self.rnum}: recipe {plan['recipe']['id']}, init {plan['init']} (scripts/loop.py)\n")
            yaml.safe_dump(t, fh, sort_keys=False)
        offset = [os.path.getsize(os.path.join(tdir, "metrics.jsonl")) if os.path.exists(os.path.join(tdir, "metrics.jsonl")) else 0]
        mpath = os.path.join(tdir, "metrics.jsonl")

        def relay():
            if os.path.exists(mpath):
                with open(mpath, "rb") as fh:
                    fh.seek(offset[0])
                    data = fh.read()
                cut = data.rfind(b"\n") + 1
                offset[0] += cut
                for line in data[:cut].decode("utf-8", "replace").splitlines():
                    try:
                        m = json.loads(line)
                    except ValueError:
                        continue
                    if "loss" in m and "step" in m and "event" not in m:
                        self.run.metric(stage="train", round=self.rnum, **m)
            st = self.read_json(os.path.join(tdir, "status.json")) or {}
            self.status("train", f"step {st.get('step')}/{st.get('max_steps')} ({st.get('state')})")
            return True

        cmd = [PY, "-u", os.path.join(ROOT, "scripts", "train_longrun.py"), "--config", ypath, "--run-dir", tdir, "--resume"]
        rc = self.run_child(cmd, "train_longrun.log", stop_dir=tdir, monitor=relay, interval=20)
        relay()
        st = self.read_json(os.path.join(tdir, "status.json")) or {}
        if st.get("state") == "paused" or self.stopping():
            raise fr.Paused()
        if rc != 0 or st.get("state") != "finished":
            raise RuntimeError(f"training ended with exit code {rc}, state {st.get('state')}: {st.get('error')}")
        s = self.read_json(os.path.join(tdir, "summary.json")) or {}
        if plan["init_adapter"] and not s.get("init_adapter"):
            raise RuntimeError(f"train_longrun.py did not report loading init_adapter {plan['init_adapter']}: the round "
                               f"would have trained a fresh LoRA instead of continuing the best adapter")
        return self.mark_done("train", {k: s.get(k) for k in ("global_step", "total_steps", "trainable_params", "rows",
                                                               "rows_dropped_too_long", "tokens", "peak_reserved_gib",
                                                               "session_seconds", "adapter", "metrics", "data_sha256",
                                                               "init_adapter")})

    def round_gguf(self):
        return os.path.join(self.rdir, "convert", f"loop-r{self.rnum:03d}-F16-LoRA.gguf")

    def convert_round(self):
        out = self.round_gguf()
        os.makedirs(os.path.dirname(out), exist_ok=True)
        rc = self.run_child([PY, "-u", fr.CONVERT, "--base", llama.LORA_BASE_CONFIG, "--outtype", "f16", "--outfile", out,
                             os.path.join(self.rdir, "train", "adapter")], "convert_lora.log")
        if rc != 0 or not os.path.exists(out):
            raise RuntimeError(f"convert_lora_to_gguf.py exited with {rc}")
        return self.mark_done("convert", {"gguf": out, "bytes": os.path.getsize(out)})

    def valloss(self):
        vdir = os.path.join(self.rdir, "valloss")
        if not os.path.exists(os.path.join(vdir, "summary.json")):
            rc = self.run_child([PY, "-u", os.path.join(ROOT, "scripts", "val_loss.py"), "--adapter",
                                 os.path.join(self.rdir, "train", "adapter"), "--val-file",
                                 os.path.join(self.rdir, "data", "mix", "val.jsonl"), "--max-rows", "100",
                                 "--run-dir", vdir], "val_loss.log")
            self.check_stop()
            if rc != 0:
                raise RuntimeError(f"val_loss.py exited with {rc}")
        val = self.read_json(os.path.join(vdir, "summary.json")) or {}
        return self.mark_done("valloss", {k: v for k, v in val.items() if k != "per_row"})

    def confirm(self, cfg, d):
        """The kept adapter on the gate again with a fresh seed: its unbiased reference for later rounds."""
        seed = 1000 + self.rnum
        g = cfg["gate"]
        self.serve(self.gate_flags(cfg, lora=self.round_gguf()), "confirm")
        try:
            path = os.path.join(self.rdir, f"gate.seed{seed}.jsonl")
            rows = E.score(self.server.url, E.read_jsonl(E.GATE_PATH), path, seed, g["max_tokens"],
                           E.gate_check(gt.run_io_tests, gt.run_assert_tests, gt.extract_code),
                           lambda u, m, s, mt: ew.chat_request(u, m, s, mt), ew.count_tokens, g["budget"],
                           concurrency=g.get("concurrency", 4), stop_check=self.stopping, log=self.log,
                           on_row=lambda r, n, tot, tps: self.status("confirm", f"gate {n}/{tot}"))
        finally:
            self.unserve()
        best_old = [r for r in E.read_jsonl(self.state["best"]["gate_rows"]) if r["seed"] == self.state["best"]["gate_seed"]]
        return self.mark_done("confirm", {"gate_rows": path, "gate_seed": seed, "pass": sum(r["pass"] for r in rows),
                                          "n": len(rows), "vs_previous_best": E.compare(best_old, rows)})

    def milestone(self, cfg):
        """EvalPlus seed 1 with the first run's exact scoring server, paired against the base's first-run answers."""
        fdir = cfg.get("first_run_dir") or os.path.join(RESULTS_DIR, "first-run")
        cal = self.read_json(os.path.join(fdir, "stages", "calibrate.done.json")) or {}
        flags = llama.scoring_flags(lora=self.round_gguf(), extra=["--reasoning-budget", str(fr.BUDGET_SCORE)]
                                    + fr.SAMPLER_FLAGS + cal.get("chosen_extra_flags", []))
        d = os.path.join(self.rdir, "evalplus")
        raw = {ds: os.path.join(d, f"{ds}.raw.jsonl") for ds in ew.DATASETS}
        jobs = [(ds, t) for ds in ew.DATASETS for t in ew.load_problems(ds)]
        self.serve(flags, "evalplus")
        try:
            ew.generate_tasks(jobs, self.server.url, raw, seed=1, concurrency=4, max_tokens=ew.MAX_TOKENS,
                              reasoning_budget=fr.BUDGET_SCORE, log=self.log, stop_check=self.stopping,
                              on_row=lambda r, n, tot, tps: self.status("milestone", f"EvalPlus {n}/{tot}"))
        finally:
            self.unserve()
        res = {"datasets": {}}
        for ds in ew.DATASETS:
            res["datasets"][ds] = ew.evaluate(ds, ew.sanitize_file(ds, raw[ds]), parallel=8)
        write_json(os.path.join(d, "result.json"), res)
        base = self.read_json(os.path.join(fdir, "score", "base.json"))
        out = {}
        for ds in ew.DATASETS:
            r = res["datasets"][ds]
            out[ds] = {"base": r["base"], "plus": r["plus"]}
            if base:
                pb, pa = base["datasets"][ds]["per_task"], r["per_task"]
                tasks = sorted(set(pb) & set(pa))
                for key in ("base_pass", "plus_pass"):
                    out[ds][f"vs_base_{key}"] = fr.paired([int(pa[t][key]) for t in tasks], [int(pb[t][key]) for t in tasks])
        return self.mark_done("milestone", {"datasets": out})

    def finish(self, cfg, plan, ev, d, conf, mile):
        rec = self.round_record()
        best = self.state["best"]
        if d["keep"]:
            self.state["best"] = {"round": self.rnum, "name": f"r{self.rnum:03d}",
                                  "adapter": os.path.join(self.rdir, "train", "adapter"), "gguf": self.round_gguf(),
                                  "gate_rows": conf["gate_rows"], "gate_seed": conf["gate_seed"],
                                  "lineage": (plan["lineage"] if plan["init"] == "base_lineage" else best["lineage"])
                                  + [[n, idx] for n, idx in plan["slices"].items()],
                                  "lora_shape": lora_shape(plan["train"])}
            self.state["rejects_in_row"] = 0
            rec["status"] = "kept"
        else:
            self.state["rejects_in_row"] += 1
            rec["status"] = "rejected"
            rec["freed_bytes"] = safe_delete(self.rdir, ["train/adapter", "train/checkpoints", "train/milestones",
                                                         "train/branches", "convert"], self.log)
        if plan["recipe"]["id"] != "default" and plan["recipe"]["id"] not in self.state["recipes_done"]:
            self.state["recipes_done"].append(plan["recipe"]["id"])
        rec.update(gate=f"{ev['gate_pass']}/{ev['gate_n']}", gate_diff=d["gate"]["diff"], p=d["gate"]["p_one_sided"],
                   noncoding=ev["noncoding_accuracy"], reasons=d["reasons"], best_before=d["best_round"],
                   evalplus=(mile or {}).get("datasets"), finished=time.strftime("%Y-%m-%d %H:%M:%S"))
        self.save()
        self.write_report(cfg, rec, ev, d, plan, conf, mile)
        self.write_summary()
        return self.mark_done("finish", {"status": rec["status"]})

    # ----------------------------------------------------------------------------------------- reports

    def write_report(self, cfg, rec, ev, d, plan=None, conf=None, mile=None):
        g, cc, oci, nc = d["gate"], d["gate_cc"], d["gate_oci"], d["noncoding"]
        L = [f"# Loop round {self.rnum} ({rec.get('name') or 'r%03d' % self.rnum}): {rec['status'].upper()}", "",
             f"Compared with round {d['best_round']} (the best so far). Rules: {json.dumps(d['rules'])}.", ""]
        if d["reasons"]:
            L += ["Not kept because: " + "; ".join(d["reasons"]) + ".", ""]
        L += ["| set | n | best | this round | diff | wins / losses | one-sided p |", "|---|---|---|---|---|---|---|"]
        for name, c in (("gate (all)", g), ("CodeContests", cc), ("OpenCodeInstruct held-out", oci)):
            if c["n"]:
                L.append(f"| {name} | {c['n']} | {c['best']:.4f} | {c['candidate']:.4f} | {c['diff']:+.4f} | "
                         f"{c['wins']} / {c['losses']} | {c['p_one_sided']:.4f} |")
        if nc["n"]:
            L.append(f"| non-coding (vs base, mean of seeds) | {nc['n']} | {nc['best']:.4f} | {nc['candidate']:.4f} | "
                     f"{nc['diff']:+.4f} | {nc['wins']} / {nc['losses']} | - |")
        L += ["", f"Gate answers: finish reasons {ev.get('gate_finish')}, reasoning budget hit {ev.get('gate_budget_hits')}."]
        for s in ev.get("samples") or []:
            L.append(f"- sample {s['name']}: {s['finish_reason']}, {s['completion_tokens']} tokens, loop suspected "
                     f"{s['loop_suspect']}")
        if plan:
            L += ["", "## Recipe and data", "", f"Recipe `{plan['recipe']['id']}`: {plan['recipe'].get('note', '')}",
                  f"Init: {plan['init']}" + (f" ({plan['init_adapter']})" if plan["init_adapter"] else ""),
                  f"Fresh rows: {json.dumps({n: len(i) for n, i in plan['slices'].items()})}; earlier kept rows mixed "
                  f"back in: {sum(len(i) for _, i in plan.get('replay') or [])}; rows from the best's lineage (retrain "
                  f"from the base): {sum(len(i) for _, i in plan['lineage'])}.", "",
                  (self.done("data") or {}).get("card", ""),
                  "", "## Training", "", json.dumps({k: v for k, v in (self.done("train") or {}).items()
                                                     if k not in ("metrics",)}, default=str)]
            vl = self.done("valloss") or {}
            if vl.get("all"):
                a = vl["all"]
                L.append(f"\nVal answer-token loss {a['base']['answer_token_loss']:.4f} (base) -> "
                         f"{a['adapter']['answer_token_loss']:.4f} (this adapter), {a['rows']} rows.")
        if conf:
            c = conf["vs_previous_best"]
            L += ["", f"Confirm (fresh seed {conf['gate_seed']}): {conf['pass']}/{conf['n']}; vs previous best "
                      f"{c['diff']:+.4f} ({c['wins']} / {c['losses']}, p {c['p_one_sided']:.4f})."]
        if mile:
            L += ["", "## EvalPlus (seed 1, the first run's scoring server)", "", "| | base tests | base+extra | vs base (base+extra) |",
                  "|---|---|---|---|"]
            for ds, m in mile["datasets"].items():
                vb = m.get("vs_base_plus_pass")
                L.append(f"| {ds} | {m['base']:.4f} | {m['plus']:.4f} | " + (
                    f"{vb['diff']:+.4f} [{vb['ci95'][0]:+.4f}, {vb['ci95'][1]:+.4f}], p {vb['p_permutation']:.4f}"
                    if vb else "-") + " |")
        with open(os.path.join(self.rdir, "report.md"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(L) + "\n")

    def write_summary(self):
        best = self.state.get("best") or {}
        L = ["# Improvement loop", "", f"Updated {time.strftime('%Y-%m-%d %H:%M:%S')}. Best so far: round "
             f"{best.get('round')} ({best.get('name')}). Rejects in a row: {self.state['rejects_in_row']}.", "",
             "| round | recipe | init | rows | gate | diff vs best | p | non-coding | result | EvalPlus+ HE / MBPP |",
             "|---|---|---|---|---|---|---|---|---|---|"]
        for r in self.state["rounds"]:
            ep = r.get("evalplus") or {}
            eps = " / ".join(f"{ep[ds]['plus']:.3f}" for ds in ew.DATASETS if ds in ep) or "-"
            diff = f"{r['gate_diff']:+.4f}" if isinstance(r.get("gate_diff"), (int, float)) else "-"
            p = f"{r['p']:.4f}" if isinstance(r.get("p"), (int, float)) else "-"
            ncs = f"{r['noncoding']:.3f}" if isinstance(r.get("noncoding"), (int, float)) else "-"
            L.append(f"| {r['round']} | {r.get('recipe', r.get('name', '-'))} | {r.get('init', '-')} | {r.get('rows', '-')} | "
                     f"{r.get('gate', '-')} | {diff} | {p} | {ncs} | {r['status']} | {eps} |")
        with open(os.path.join(self.dir, "summary.md"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(L) + "\n")


def _count(xs):
    out = {}
    for x in xs:
        out[x] = out.get(x, 0) + 1
    return out


