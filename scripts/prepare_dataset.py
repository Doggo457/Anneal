"""Turn a public code-instruction dataset into train/val JSONL in chat format, with basic cleaning
and an optional contamination check against HumanEval+ / MBPP+ prompts.

Works on any machine (CPU only). Run it on this PC before the EVO-X2 arrives to see what the
training data actually looks like.

Usage:
  python scripts/prepare_dataset.py --max-samples 200                 # quick look
  python scripts/prepare_dataset.py --max-samples 10000 --decontaminate
  python scripts/prepare_dataset.py --dataset m-a-p/CodeFeedback-Filtered-Instruction \
      --prompt-field query --response-field answer --max-samples 10000

Thinking mode is ON for this project, so training rows must contain a <think>...</think> trace:
  # ready-made traces. OpenCodeReasoning has two configs, so --config is required, and --data-files
  # pulls 3 of its 30 shards (~0.8 GB) instead of the whole 8.3 GB split. The first shards are all
  # CodeContests, so the three are spread across the split.
  python scripts/prepare_dataset.py --dataset nvidia/OpenCodeReasoning --config split_0 \
      --data-files split_0/train-00000-of-00030.parquet,split_0/train-00015-of-00030.parquet,split_0/train-00027-of-00030.parquet \
      --prompt-field input --response-field output --require-think \
      --tokenizer Qwen/Qwen3.8-27B --max-tokens 8192 --max-per-prompt 3 --decontaminate --report-field source --report-field difficulty \
      --max-samples 2000 --out data/processed/ocr
  # traces generated by the base model itself (scripts/generate_traces.py writes messages-format JSONL)
  python scripts/prepare_dataset.py --from-jsonl data/raw/self_traces.jsonl --require-think \
      --tokenizer Qwen/Qwen3.8-27B --max-tokens 8192 --decontaminate --out data/processed/self
If the trace and the answer are separate columns, add --reasoning-field <col> and they are joined as
<think>\n{trace}\n</think>\n\n{answer}.

Length filter: with --tokenizer, each row is rendered through the model's chat template and counted
in real tokens, and rows over --max-tokens are dropped, never truncated, because a cut-off trace
teaches unfinished thinking. Without --tokenizer it falls back to --max-chars (14000 is roughly
3,500 tokens at 4 chars per token, but code-heavy text often runs nearer 3, so the token count is the
safe check: the trainer silently truncates anything over seq_len).

--max-samples is the number of rows to KEEP. Rows are drawn in shuffled order and filtered until that
many pass, so the length and contamination filters no longer shrink the output below what you asked for.

--max-per-prompt N keeps up to N different responses to the same question (default 1). OpenCodeReasoning
has about 25 R1 solutions per question; 2 to 4 gives more rows from the questions that fit the length cap.
Identical responses are always dropped, and the validation split is made by question, so no question
appears in both train and val.

Decontamination (--decontaminate) drops a row if it shares any 13-token window with a HumanEval+ or
MBPP+ prompt, or if its prompt has token-set Jaccard similarity above 0.8 with one. Both counts go in
the data card. Needs `pip install evalplus`.

--decontaminate-gate FILE (data/eval/decontam_extra.jsonl from build_evalsets.py) also drops rows that overlap the
improvement loop's held-out gate or non-coding questions: at least 30% of a held-out problem's 13-grams in the row,
or Jaccard > 0.8 on the prompt (anneal/evalsets.py OverlapIndex; a share, because contest statements share
boilerplate that an any-match rule would flag everywhere).

Output: <out>/train.jsonl, val.jsonl, and data_card.md with the counts.
Each row: {"messages": [{"role": "user", ...}, {"role": "assistant", ...}]}
"""
import argparse
import collections
import json
import os
import random
import re
import sys

from datasets import load_dataset

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from anneal.rowkeys import LANG_ALIASES, answer_text, fence_languages, message_reasoning  # noqa: E402  (standard library only)

DEFAULT_SYSTEM = None  # e.g. "You are a careful, concise coding assistant." Leave None to train without one.


def tokens(text: str):
    return re.findall(r"[a-z0-9_]+", text.lower())


def ngrams(toks, n):
    return {tuple(toks[i:i + n]) for i in range(len(toks) - n + 1)}


def benchmark_prompts():
    """HumanEval+ and MBPP+ prompts from EvalPlus. Returns None if evalplus isn't installed."""
    try:
        from evalplus.data import get_human_eval_plus, get_mbpp_plus
    except ImportError:
        return None
    return [item["prompt"] for ds in (get_human_eval_plus(), get_mbpp_plus()) for item in ds.values()]


class Decontaminator:
    """13-gram overlap (prompt + response) and token-set Jaccard (prompt) against benchmark prompts."""

    def __init__(self, prompts, n=13, jaccard=0.8):
        self.n, self.jaccard = n, jaccard
        self.grams = set()
        self.sets = []
        for p in prompts:
            toks = tokens(p)
            self.grams |= ngrams(toks, n)
            s = frozenset(toks)
            if s:
                self.sets.append(s)
        self.sets.sort(key=len)
        self.sizes = [len(s) for s in self.sets]

    @classmethod
    def from_evalplus(cls, n=13, jaccard=0.8, extra=None):
        """EvalPlus prompts, plus any extra evaluation questions (e.g. the non-coding check) from a file:
        JSONL with a "prompt", "question" or "text" field, or plain text with one question per line."""
        prompts = benchmark_prompts()
        if prompts is None:
            return None
        if extra:
            with open(extra, encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        r = json.loads(line)
                        line = next((r[k] for k in ("prompt", "question", "text") if isinstance(r, dict) and k in r), line)
                    except json.JSONDecodeError:
                        pass
                    prompts.append(str(line))
        return cls(prompts, n, jaccard)

    def max_jaccard(self, text):
        a = frozenset(tokens(text))
        if not a:
            return 0.0
        # J(a, b) > t needs t*|a| <= |b| <= |a|/t, so only that size band can match.
        lo, hi = self.jaccard * len(a), len(a) / self.jaccard
        best = 0.0
        for size, b in zip(self.sizes, self.sets):
            if size < lo:
                continue
            if size > hi:
                break
            inter = len(a & b)
            best = max(best, inter / (len(a) + size - inter))
        return best

    def check(self, prompt, response=""):
        """Returns None if clean, else 'ngram' or 'jaccard'."""
        if ngrams(tokens(prompt + " " + response), self.n) & self.grams:
            return "ngram"
        if self.max_jaccard(prompt) > self.jaccard:
            return "jaccard"
        return None


def parse_where(spec):
    """COL=VALUE or COL~TEXT -> (col, op, value)."""
    for op in ("=", "~"):
        col, sep, val = spec.partition(op)
        if sep and col and "=" not in col and "~" not in col:
            return col.strip(), op, val.strip().lower()
    raise SystemExit(f"--where must be COL=VALUE or COL~TEXT, got {spec!r}")


def where_ok(value, op, want):
    v = "" if value is None else str(value).strip().lower()
    return v == want if op == "=" else want in v


def load_rows(name, config, split, data_files):
    """load_dataset with an optional config name and an optional shard subset (comma-separated)."""
    files = [f.strip() for f in data_files.split(",") if f.strip()] if data_files else None
    return load_dataset(name, config, data_files=files, split="train" if files else split)


class TokenCounter:
    """Exact token count of a chat row through the model's own chat template."""

    def __init__(self, name):
        from transformers import AutoTokenizer

        self.tok = AutoTokenizer.from_pretrained(name)

    def __call__(self, messages):
        text = self.tok.apply_chat_template(messages, tokenize=False)
        return len(self.tok(text, add_special_tokens=False)["input_ids"])


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dataset", default="ise-uiuc/Magicoder-OSS-Instruct-75K")
    p.add_argument("--config", default=None, help="dataset config name (OpenCodeReasoning needs split_0 or split_1)")
    p.add_argument("--split", default="train")
    p.add_argument("--data-files", default=None,
                   help="comma-separated shard paths inside the dataset repo, to avoid downloading every shard")
    p.add_argument("--from-jsonl", default=None,
                   help="load a local messages-format JSONL (e.g. from generate_traces.py) instead of --dataset")
    p.add_argument("--prompt-field", default="problem")
    p.add_argument("--response-field", default="solution")
    p.add_argument("--reasoning-field", default=None,
                   help="column holding the reasoning trace; joined into the response as a <think> block")
    p.add_argument("--require-think", action="store_true",
                   help="drop rows whose response doesn't open with a non-empty <think> block (use this: thinking "
                        "mode is ON, and every training row carries the teacher's reasoning)")
    p.add_argument("--max-samples", type=int, default=None, help="rows to keep (after all filters)")
    p.add_argument("--max-per-prompt", type=int, default=1,
                   help="responses kept per question (OpenCodeReasoning has ~25 per question)")
    p.add_argument("--min-chars", type=int, default=40, help="drop rows with prompt or response shorter than this")
    p.add_argument("--max-chars", type=int, default=8000,
                   help="length limit when no --tokenizer is given. ~4 chars per token; 14000 for seq_len 4096")
    p.add_argument("--tokenizer", default=None,
                   help="HF id or local path of the model tokenizer, e.g. Qwen/Qwen3.8-27B; enables --max-tokens")
    p.add_argument("--max-tokens", type=int, default=8192, help="drop rows longer than this (needs --tokenizer)")
    p.add_argument("--val-fraction", type=float, default=0.02)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--decontaminate", action="store_true", help="drop rows overlapping HumanEval+/MBPP+ prompts")
    p.add_argument("--decontaminate-extra", default=None,
                   help="file of extra evaluation questions to decontaminate against (JSONL or one per line)")
    p.add_argument("--where", action="append", default=[],
                   help="keep rows where COL=VALUE (exact, case-insensitive) or COL~TEXT (contains, case-insensitive); "
                        "repeatable, all must hold")
    p.add_argument("--decontaminate-gate", default=None,
                   help="data/eval/decontam_extra.jsonl: drop rows overlapping the loop's held-out problems")
    p.add_argument("--ngram", type=int, default=13)
    p.add_argument("--jaccard", type=float, default=0.8)
    p.add_argument("--drop-answer-lang", action="append", default=[],
                   help="drop rows whose answer (after the think block) has a code block in this language, e.g. python "
                        "(21 Oct 2026: Python is the lowest priority); repeatable. Aliases fold as in "
                        "anneal/rowkeys.py fence_languages")
    p.add_argument("--report-field", action="append", default=[],
                   help="column to tabulate before/after filtering in the data card (repeatable), e.g. difficulty")
    p.add_argument("--out", default="data/processed")
    args = p.parse_args()

    random.seed(args.seed)
    if args.from_jsonl:
        # Rows are already {"messages": [...]}; map them onto prompt/response so the same filters apply.
        print(f"Loading {args.from_jsonl} ...")
        ds = load_dataset("json", data_files=args.from_jsonl, split="train")
        ds = ds.map(lambda r: {"problem": r["messages"][-2]["content"], "solution": r["messages"][-1]["content"]},
                    remove_columns=ds.column_names)
        args.prompt_field, args.response_field, args.dataset = "problem", "solution", args.from_jsonl
    else:
        print(f"Loading {args.dataset} [{args.config or 'default'} / {args.split}] ...")
        ds = load_rows(args.dataset, args.config, args.split, args.data_files)
    print(f"  {len(ds)} rows, columns: {ds.column_names}")
    if args.prompt_field not in ds.column_names or args.response_field not in ds.column_names:
        raise SystemExit(f"Fields not found. Use --prompt-field/--response-field from: {ds.column_names}")
    for f in args.report_field:
        if f not in ds.column_names:
            raise SystemExit(f"--report-field {f} not in columns: {ds.column_names}")
    wheres = [parse_where(w) for w in args.where]
    for col, _, _ in wheres:
        if col not in ds.column_names:
            raise SystemExit(f"--where {col} not in columns: {ds.column_names}")

    ds = ds.shuffle(seed=args.seed)
    count_tokens = TokenCounter(args.tokenizer) if args.tokenizer else None
    length_rule = f"max {args.max_tokens} tokens ({args.tokenizer} chat template)" if count_tokens \
        else f"max {args.max_chars} chars"

    counts = collections.Counter({k: 0 for k in ("examined", "too_short", "too_long", "no_think", "answer_lang", "duplicate",
                                                 "contaminated_ngram", "contaminated_jaccard", "contaminated_gate",
                                                 "filtered_where")})
    seen_by = {f: collections.Counter() for f in args.report_field}
    kept_by = {f: collections.Counter() for f in args.report_field}
    per_prompt = collections.Counter()
    seen_pairs = set()
    deco = Decontaminator.from_evalplus(args.ngram, args.jaccard, args.decontaminate_extra) if args.decontaminate else None
    if args.decontaminate and deco is None:
        print("  evalplus not installed; skipping decontamination (pip install evalplus)")
    gate = None
    if args.decontaminate_gate:
        from anneal.evalsets import OverlapIndex
        gate = OverlapIndex.from_jsonl(args.decontaminate_gate)
        if not len(gate):
            raise SystemExit(f"{args.decontaminate_gate} holds no problems")
        print(f"  held-out overlap check against {len(gate)} problems from {args.decontaminate_gate}")
    token_lengths = []
    drop_langs = {LANG_ALIASES.get(x.strip().lower(), x.strip().lower()) for x in args.drop_answer_lang}
    kept_langs = collections.Counter()  # rows per language of the answer's code blocks

    rows = []
    for ex in ds:
        if args.max_samples and len(rows) >= args.max_samples:
            break
        counts["examined"] += 1
        if wheres and not all(where_ok(ex.get(c), op, v) for c, op, v in wheres):
            counts["filtered_where"] += 1
            continue
        for f in args.report_field:
            seen_by[f][str(ex[f])] += 1
        prompt = (ex[args.prompt_field] or "").strip()
        response = (ex[args.response_field] or "").strip()
        if args.reasoning_field:
            reasoning = (ex.get(args.reasoning_field) or "").strip()
            if reasoning and "<think>" not in response:
                response = f"<think>\n{reasoning}\n</think>\n\n{response}"
        if args.require_think and not message_reasoning({"content": response}):  # no or an empty <think> block
            counts["no_think"] += 1
            continue
        langs = fence_languages(answer_text(response))
        if drop_langs and drop_langs.intersection(langs):
            counts["answer_lang"] += 1
            continue
        if len(prompt) < args.min_chars or len(response) < args.min_chars:
            counts["too_short"] += 1
            continue
        key = prompt.lower()
        pair = hash((key, response))
        if per_prompt[key] >= args.max_per_prompt or pair in seen_pairs:
            counts["duplicate"] += 1
            continue
        messages = []
        if DEFAULT_SYSTEM:
            messages.append({"role": "system", "content": DEFAULT_SYSTEM})
        messages += [{"role": "user", "content": prompt}, {"role": "assistant", "content": response}]
        if count_tokens:
            if len(prompt) + len(response) > 8 * args.max_tokens:  # can't fit at any ratio; skip tokenising
                counts["too_long"] += 1
                continue
            n_tok = count_tokens(messages)
            if n_tok > args.max_tokens:
                counts["too_long"] += 1
                continue
        elif len(prompt) + len(response) > args.max_chars:
            counts["too_long"] += 1
            continue
        if deco is not None:
            hit = deco.check(prompt, response)
            if hit:
                counts[f"contaminated_{hit}"] += 1
                continue
        if gate is not None and gate.hits(prompt + "\n" + response, jaccard_text=prompt):
            counts["contaminated_gate"] += 1
            continue
        per_prompt[key] += 1
        seen_pairs.add(pair)
        if count_tokens:
            token_lengths.append(n_tok)
        for f in args.report_field:
            kept_by[f][str(ex[f])] += 1
        kept_langs.update(set(langs) or {"(no code block)"})
        rows.append({"messages": messages})

    if not rows:
        raise SystemExit(f"No rows survived the filters: {dict(counts)}")
    if args.max_samples and len(rows) < args.max_samples:
        print(f"  note: only {len(rows)} rows passed the filters (asked for {args.max_samples})")

    # Split by question so several responses to one question never straddle train and val.
    groups = collections.defaultdict(list)
    for r in rows:
        groups[r["messages"][-2]["content"].lower()].append(r)
    keys = list(groups)
    random.shuffle(keys)
    n_val_target = max(1, int(len(rows) * args.val_fraction))
    val, train = [], []
    for k in keys:
        (val if len(val) < n_val_target else train).extend(groups[k])
    random.shuffle(train)

    os.makedirs(args.out, exist_ok=True)
    for name, data in (("train", train), ("val", val)):
        path = os.path.join(args.out, f"{name}.jsonl")
        with open(path, "w", encoding="utf-8") as f:
            for r in data:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"  wrote {len(data):6d} rows -> {path}")

    card = os.path.join(args.out, "data_card.md")
    with open(card, "w", encoding="utf-8") as f:
        f.write(f"# Data card\n\nSource: `{args.dataset}` config `{args.config or 'default'}` split `{args.split}`\n")
        if args.data_files:
            f.write(f"Shards: `{args.data_files}`\n")
        f.write("Licence: FILL IN from the dataset card, with the URL.\n\n")
        f.write("| Stage | Rows |\n|---|---|\n")
        for k, v in counts.items():
            f.write(f"| {k} | {v} |\n")
        f.write(f"| kept | {len(rows)} |\n| questions | {len(groups)} |\n| train | {len(train)} |\n| val | {len(val)} |\n")
        f.write(f"\nFilters: min {args.min_chars} chars, {length_rule}, up to {args.max_per_prompt} response(s) per question "
                f"(identical responses removed), val split by question, "
                f"require_think={'on' if args.require_think else 'off'}, "
                f"decontamination={'on' if deco is not None else 'off'} "
                f"({args.ngram}-gram on prompt+response and Jaccard > {args.jaccard} on prompt, "
                f"vs HumanEval+/MBPP+), row filters {args.where or 'none'}, held-out overlap check="
                f"{'on (' + args.decontaminate_gate + ')' if gate is not None else 'off'}.\n")
        if token_lengths:
            s = sorted(token_lengths)
            q = lambda x: s[min(len(s) - 1, int(x * len(s)))]  # noqa: E731
            f.write(f"\nKept-row length in tokens: min {s[0]}, median {q(0.5)}, p90 {q(0.9)}, max {s[-1]}.\n")
        f.write(f"\nDropped for answer code in {sorted(drop_langs) or 'no language'}. Kept rows by the languages of the "
                "answer's code blocks (a row counts once per language):\n\n| Language | Rows |\n|---|---|\n")
        for lang, n in kept_langs.most_common():
            f.write(f"| {lang or '(untagged)'} | {n} |\n")
        for fld in args.report_field:
            f.write(f"\n## `{fld}` before and after filtering\n\n| Value | Examined | Kept | Kept % |\n|---|---|---|---|\n")
            for val_, n in seen_by[fld].most_common():
                k = kept_by[fld][val_]
                f.write(f"| {val_} | {n} | {k} | {100 * k / n:.1f} |\n")
    print(f"  wrote {card}")

    print("\nCounts:", dict(counts))
    print("\nTwo random examples:")
    for r in random.sample(train, min(2, len(train))):
        user = r["messages"][-2]["content"]
        asst = r["messages"][-1]["content"]
        print("-" * 70)
        print("USER:", user[:500].replace("\n", "\n      "))
        print("ASSISTANT:", asst[:500].replace("\n", "\n           "))
    print("-" * 70)
    print("Read at least twenty of these before training. If they look wrong to you, the model will learn wrong.")


if __name__ == "__main__":
    main()
